#!/bin/sh
# Compiles EDuke32's EIN build to WebAssembly: eduke32.js and eduke32.wasm in the directory given.
# Run inside the emsdk image, from the source tree engine/Containerfile lays out (the fork
# with webgl.patch, ein.patch and files/).
set -eu
out=$1

# EIN=1 (Common.mak): an ES module for a Web Worker, -sMODULARIZE -sEXPORT_ES6
# -sEXPORT_NAME=createEDuke32 -sENVIRONMENT=worker -sINVOKE_RUN=0 -sEXIT_RUNTIME=1 -sASYNCIFY with a
# 16 MB stack for it, -sLEGACY_GL_EMULATION on WebGL 2, the _ein_* exports. Four compilers at a time
# keep the build's memory small beside a running EiN.
make PLATFORM=EMSCRIPTEN EIN=1 -j"${EMCC_CORES:-4}"

# The glue is headed with Deno's ignore comments, so core's `deno fmt` and `deno lint` pass over the
# generated file.
{ printf '%s\n' '// deno-fmt-ignore-file' '// deno-lint-ignore-file' '// Generated by engine/Containerfile with Emscripten. Do not edit.'; cat eduke32.js; } > "$out/eduke32.js"
cp eduke32.wasm "$out/eduke32.wasm"
