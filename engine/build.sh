#!/bin/sh
# Compiles Duke Nukem 3D (Chocolate Duke3D with this module's platform layer) to WebAssembly:
# duke3d.js and duke3d.wasm in the directory given. Run inside the emsdk image, from a source tree
# laid out as engine/Containerfile lays it out: Engine/ and Game/ as Chocolate Duke3D has them, this
# module's engine/*.c beside them and its engine/include/ as include/.
set -eu
out=$1
extra=${2:-}

# The engine's and the game's sources as Chocolate Duke3D's CMake lists them, less SDL's display,
# sound and music drivers, and this build's in their place.
ENGINE="cache draw engine filesystem fixedPoint_math mmulti tiles"
GAME="actors animlib config control game gamedef global keyboard menues player premap rts scriplib sector sounds console cvar_defs cvars"
AUDIO="dpmi fx_man ll_man multivoc mv_mix mvreverb pitch"
EIN="display_ein dsl_ein music_ein game_ein"
# Apogee's AdLib MIDI driver and sequencer from the original Chocolate Duke3D, which the music plays
# through (music_ein.c), with DOS's headers stood in for in al/; and Nuked OPL3, the chip.
AL="al/al_midi al/gmtimbre al/midi"
OPL="opl/opl3"

# The game's code is not written for strict aliasing, and defines some globals in headers.
CFLAGS="-O2 -std=gnu99 -w -Wno-error=incompatible-pointer-types -Wno-error=int-conversion -Wno-error=implicit-function-declaration -Wno-error=implicit-int -Wno-error=return-type -DUNIX -fno-strict-aliasing -fcommon -DCHECK_XDUKE_REV -Iinclude -IEngine/src -IGame/src -IGame/src/audiolib"

mkdir -p obj
objects=
for name in $ENGINE; do objects="$objects Engine/src/$name.c"; done
for name in $GAME; do objects="$objects Game/src/$name.c"; done
for name in $AUDIO; do objects="$objects Game/src/audiolib/$name.c"; done
for name in $EIN $AL $OPL; do objects="$objects $name.c"; done

# Two compilers at a time keep the build's memory small beside a running EiN.
echo $objects | tr ' ' '\n' | xargs -P "${EMCC_CORES:-2}" -I{} sh -c 'emcc '"$CFLAGS"' -Ial -c {} -o obj/$(echo {} | tr / _).o'

# The game's loops block, so it runs under ASYNCIFY and waits for the worker's ticks
# (display_ein.c). It runs in the module's engine worker (ui/duke3d/engine-worker.ts), which starts
# its main itself. The glue is headed with Deno's ignore comments, so core's `deno fmt` and
# `deno lint` pass over the generated file.
emcc -O2 obj/*.o -o "$out/duke3d.js" $extra \
  -sMODULARIZE=1 -sEXPORT_ES6=1 -sEXPORT_NAME=createDuke3D \
  -sENVIRONMENT=worker \
  -sASYNCIFY=1 -sASYNCIFY_STACK_SIZE=65536 \
  -sALLOW_MEMORY_GROWTH=1 -sINITIAL_MEMORY=128MB -sSTACK_SIZE=1MB \
  -sEXIT_RUNTIME=1 -sINVOKE_RUN=0 \
  -sEXPORTED_FUNCTIONS=_main,_ein_key,_ein_write_config,_ein_mouse,_ein_mouse_button,_ein_screen,_ein_width,_ein_height,_ein_frames,_ein_audio_rate,_ein_audio_render,_ein_menu,_malloc,_free \
  -sEXPORTED_RUNTIME_METHODS=FS,HEAPU8,HEAP16,HEAPU32,callMain,stringToNewUTF8 \
  -sFORCE_FILESYSTEM=1
{ printf '%s\n' '// deno-fmt-ignore-file' '// deno-lint-ignore-file' '// Generated by engine/Containerfile with Emscripten. Do not edit.'; cat "$out/duke3d.js"; } > "$out/duke3d.js.new"
mv "$out/duke3d.js.new" "$out/duke3d.js"
